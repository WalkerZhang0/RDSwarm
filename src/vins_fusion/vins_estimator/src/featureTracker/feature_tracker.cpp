void FeatureTracker::setPrediction(map<int, Eigen::Vector3d> &predictPts)
{
    hasPrediction = true;
    predict_pts.clear();
    predict_pts_debug.clear();
    map<int, Eigen::Vector3d>::iterator itPredict;
    for (size_t i = 0; i < ids.size(); i++)
    {
        //printf("prevLeftId size %d prevLeftPts size %d\n",(int)prevLeftIds.size(), (int)prevLeftPts.size());
        int id = ids[i];
        itPredict = predictPts.find(id);
        if (itPredict != predictPts.end())
        {
            Eigen::Vector2d tmp_uv;
            m_camera[0]->spaceToPlane(itPredict->second, tmp_uv);
            predict_pts.push_back(cv::Point2f(tmp_uv.x(), tmp_uv.y()));
            predict_pts_debug.push_back(cv::Point2f(tmp_uv.x(), tmp_uv.y()));
        }
        else
            predict_pts.push_back(prev_pts[i]);
    }
}


void FeatureTracker::removeOutliers(set<int> &removePtsIds)
{
    std::set<int>::iterator itSet;
    vector<uchar> status;
    for (size_t i = 0; i < ids.size(); i++)
    {
        itSet = removePtsIds.find(ids[i]);
        if(itSet != removePtsIds.end())
            status.push_back(0);
        else
            status.push_back(1);
    }

    reduceVector(prev_pts, status);
    reduceVector(ids, status);
    reduceVector(track_cnt, status);
}

void FeatureTracker::writeFeatureDiagnostics(double total_ms,
                                             int prev_cnt,
                                             int lk_cnt,
                                             int mask_cnt,
                                             int requested_new_cnt,
                                             int new_cnt,
                                             double lk_ms,
                                             double mask_ms,
                                             double detect_ms,
                                             const string &detector_name)
{
    if (!FEATURE_DIAGNOSTICS)
        return;

    if (!feature_diagnostics_file.is_open())
    {
        feature_diagnostics_file.open(FEATURE_DIAGNOSTICS_PATH.c_str(), std::ios::out);
        if (!feature_diagnostics_file.is_open())
        {
            ROS_WARN_THROTTLE(5.0, "Failed to open feature diagnostics log: %s", FEATURE_DIAGNOSTICS_PATH.c_str());
            return;
        }
        ROS_INFO("Feature diagnostics log: %s", FEATURE_DIAGNOSTICS_PATH.c_str());
    }

    if (!feature_diagnostics_header_written)
    {
        feature_diagnostics_file
            << "frame_index,time,detector,prev_pts,lk_tracked_pts,mask_kept_pts,requested_new_pts,new_pts,final_pts,"
            << "lk_survival,avg_track_cnt,max_track_cnt,track_cnt_ge_2,track_cnt_ge_5,track_cnt_ge_10,"
            << "lk_ms,mask_ms,detect_ms,total_ms\n";
        feature_diagnostics_header_written = true;
    }

    int final_cnt = static_cast<int>(cur_pts.size());
    double lk_survival = prev_cnt > 0 ? static_cast<double>(lk_cnt) / static_cast<double>(prev_cnt) : 0.0;
    double avg_track_cnt = 0.0;
    int max_track_cnt = 0;
    int track_cnt_ge_2 = 0;
    int track_cnt_ge_5 = 0;
    int track_cnt_ge_10 = 0;

    for (size_t i = 0; i < track_cnt.size(); ++i)
    {
        int cnt = track_cnt[i];
        avg_track_cnt += cnt;
        max_track_cnt = std::max(max_track_cnt, cnt);
        if (cnt >= 2)
            ++track_cnt_ge_2;
        if (cnt >= 5)
            ++track_cnt_ge_5;
        if (cnt >= 10)
            ++track_cnt_ge_10;
    }
    if (!track_cnt.empty())
        avg_track_cnt /= static_cast<double>(track_cnt.size());

    feature_diagnostics_file
        << feature_frame_index++ << ","
        << cur_time << ","
        << detector_name << ","
        << prev_cnt << ","
        << lk_cnt << ","
        << mask_cnt << ","
        << requested_new_cnt << ","
        << new_cnt << ","
        << final_cnt << ","
        << lk_survival << ","
        << avg_track_cnt << ","
        << max_track_cnt << ","
        << track_cnt_ge_2 << ","
        << track_cnt_ge_5 << ","
        << track_cnt_ge_10 << ","
        << lk_ms << ","
        << mask_ms << ","
        << detect_ms << ","
        << total_ms << "\n";
    feature_diagnostics_file.flush();
}


